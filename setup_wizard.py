#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Interactive setup wizard for tuya-bulb-mcp.

Guides you through creating/updating the project's .env file:
  1. (optional) LAN scan to discover the bulb's device ID / IP / protocol version
  2. device id / IP / version prompts (existing .env values are used as defaults)
  3. local key prompt (hidden via getpass on a TTY; plain stdin when piped — never printed or logged)
  4. optional hard guard (TUYA_BULB_EXPECTED_DEVICE_ID)
  5. optional read-only verification (one status() call — no writes)

Usage:
  python setup_wizard.py             # interactive
  python setup_wizard.py --scan      # run a LAN scan first
  python setup_wizard.py --no-verify # skip the read-only status check
"""

import argparse
import getpass
import os
import subprocess
import sys

BASE = os.path.dirname(os.path.abspath(__file__))
ENV_PATH = os.path.join(BASE, ".env")


def load_env(path):
    cfg = {}
    if not os.path.exists(path):
        return cfg
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            cfg[k.strip()] = v.strip()
    return cfg


def upsert_env(path, values):
    """Update managed keys in place, keep unrelated lines, never touch other files."""
    kept = []
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            for line in fh.read().splitlines():
                key = line.split("=", 1)[0].strip()
                if key in values:
                    continue
                if (line.startswith("# tuya-bulb-mcp")
                        or line.startswith("# DO NOT COMMIT")):
                    continue
                kept.append(line)
    while kept and not kept[-1].strip():
        kept.pop()
    block = [
        "# tuya-bulb-mcp — local control configuration (generated by setup_wizard.py)",
        "# DO NOT COMMIT — .env is gitignored. Contains the device local key.",
    ]
    block += ["%s=%s" % (k, v) for k, v in values.items()]
    out = kept + ([""] if kept else []) + block
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    try:
        os.chmod(path, 0o600)
    except Exception:
        pass


def ask(label, default="", required=False):
    while True:
        shown = " [%s]" % default if default else ""
        try:
            val = input("  %s%s: " % (label, shown)).strip()
        except EOFError:
            val = ""
        if not val:
            val = default
        if val or not required:
            return val
        print("    This field is required.")


def ask_yes(label, default=True):
    d = "Y/n" if default else "y/N"
    try:
        val = input("  %s [%s]: " % (label, d)).strip().lower()
    except EOFError:
        return default
    if not val:
        return default
    return val in ("y", "yes")


def read_secret(prompt):
    """Hidden input on a real terminal; plain stdin when piped (agents/CI)."""
    if sys.stdin.isatty():
        return getpass.getpass(prompt)
    print(prompt, end="", flush=True)
    try:
        return sys.stdin.readline().rstrip("\r\n")
    except Exception:
        return ""


def run_scan():
    print("\n[..] Running a LAN scan (18s) to discover Tuya devices ...\n")
    try:
        subprocess.run(
            [sys.executable, "-m", "tinytuya", "scan", "18", "-nocolor", "-yes"],
            check=False,
        )
    except Exception as exc:
        print("[WARN] scan failed: %s" % exc)
        return
    print("\n  Tip: device id / IP / version are shown above (also saved to snapshot.json).")


def verify(values):
    """Read-only check using TUYA_BULB_* keys (values dict)."""
    print("\n[..] Read-only verification: calling status() once (no writes) ...")
    try:
        import tinytuya
        d = tinytuya.BulbDevice(
            values["TUYA_BULB_DEVICE_ID"], values["TUYA_BULB_IP"],
            values["TUYA_BULB_LOCAL_KEY"],
            dev_type="default", version=float(values["TUYA_BULB_VERSION"]),
            connection_timeout=6, connection_retry_limit=2, connection_retry_delay=1,
        )
        d.set_version(float(values["TUYA_BULB_VERSION"]))
        d.set_socketTimeout(8)
        data = d.status()
    except Exception as exc:
        print("[FAIL] verification error: %s: %s" % (type(exc).__name__, exc))
        return False
    if isinstance(data, dict) and "dps" in data:
        dps = data.get("dps") or {}
        power = "on" if dps.get("20") is True else ("off" if dps.get("20") is False else "?")
        print("[OK] Device responded — power=%s  mode=%s  DP22=%s  DP23=%s"
              % (power, dps.get("21"), dps.get("22"), dps.get("23")))
        print("     (read-only check — nothing was written)")
        return True
    print("[FAIL] no valid status response (check device id / IP / key / version).")
    return False


def main():
    ap = argparse.ArgumentParser(description="Interactive setup wizard for tuya-bulb-mcp")
    ap.add_argument("--scan", action="store_true", help="run a LAN scan before prompting")
    ap.add_argument("--no-verify", action="store_true", help="skip the read-only status check")
    args = ap.parse_args()

    print("=" * 64)
    print(" tuya-bulb-mcp — setup wizard")
    print("=" * 64)
    print(" Creates/updates .env (gitignored). The local key is read with hidden")
    print(" input and is never printed, logged, or committed.\n")

    cur = load_env(ENV_PATH)
    if args.scan:
        run_scan()

    def _get(key, default=""):
        return cur.get(key, default)

    dev_id = ask("Device ID (from scan)", _get("TUYA_BULB_DEVICE_ID", ""), required=True)
    ip = ask("Device IP", _get("TUYA_BULB_IP", ""), required=True)
    version = ask("Protocol version", _get("TUYA_BULB_VERSION", "3.3")) or "3.3"

    has_key = bool(cur.get("TUYA_BULB_LOCAL_KEY"))
    hint = " (leave blank to keep the current key)" if has_key else " (hidden input)"
    key = read_secret("  Local key%s: " % hint).strip()
    if not key:
        key = cur.get("TUYA_BULB_LOCAL_KEY", "")
    if not key:
        print("\n[FAIL] A local key is required.")
        print("       Tuya IoT Cloud -> your project -> device details -> Local Key.")
        return 1

    guard_default = not cur.get("TUYA_BULB_EXPECTED_DEVICE_ID") or \
        cur.get("TUYA_BULB_EXPECTED_DEVICE_ID") == dev_id
    guard = ask_yes("Set hard guard TUYA_BULB_EXPECTED_DEVICE_ID to this device id?", guard_default)

    values = {
        "TUYA_BULB_DEVICE_ID": dev_id,
        "TUYA_BULB_IP": ip,
        "TUYA_BULB_VERSION": version,
        "TUYA_BULB_LOCAL_KEY": key,
    }
    if guard:
        values["TUYA_BULB_EXPECTED_DEVICE_ID"] = dev_id

    upsert_env(ENV_PATH, values)
    print("\n[OK] .env written: %s" % ENV_PATH)

    ok = True
    if not args.no_verify:
        ok = verify(values)

    print("\n" + "-" * 64)
    print(" Next: wire it into your MCP client (see README). Example:")
    print("   command: %s" % sys.executable)
    print("   args:    %s" % os.path.join(BASE, "tuya_bulb_mcp_server.py"))
    print("-" * 64)
    return 0 if ok else 2


if __name__ == "__main__":
    sys.exit(main())
