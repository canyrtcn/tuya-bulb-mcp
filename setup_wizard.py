#!/usr/bin/env python3
"""Interactive, read-only setup for the local Tuya MCP server."""

import argparse
from datetime import datetime, timezone
import getpass
import ipaddress
import json
import os
import re
import subprocess
import sys
import tempfile

from tuya_config import read_env

BASE = os.path.dirname(os.path.abspath(__file__))
ENV_PATH = os.path.join(BASE, ".env")
BASELINE_PATH = os.path.join(BASE, "baseline_state.json")
MANAGED_KEYS = (
    "TUYA_BULB_DEVICE_ID",
    "TUYA_BULB_IP",
    "TUYA_BULB_VERSION",
    "TUYA_BULB_LOCAL_KEY",
    "TUYA_BULB_EXPECTED_DEVICE_ID",
)
WRITABLE_DPS = ("20", "21", "22", "23", "24")


def load_env(path):
    return read_env(path) if os.path.exists(path) else {}


def atomic_write(path, contents):
    """Restrict access before writing on POSIX; replace only when complete."""
    fd, temp = tempfile.mkstemp(prefix=".tuya-", dir=os.path.dirname(path))
    try:
        if os.name == "posix":
            os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            fd = -1
            stream.write(contents)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temp, path)
    finally:
        if fd >= 0:
            os.close(fd)
        if os.path.exists(temp):
            os.unlink(temp)


def upsert_env(path, values):
    """Preserve unrelated entries; replace all managed values, including guard."""
    kept = []
    if os.path.exists(path):
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh.read().splitlines():
                key = line.split("=", 1)[0].strip()
                key = key.removeprefix("export ").removeprefix("# ").lstrip("#").strip()
                if key in MANAGED_KEYS:
                    continue
                if line.startswith("# tuya-bulb-mcp") or line.startswith("# DO NOT COMMIT"):
                    continue
                kept.append(line)
    while kept and not kept[-1].strip():
        kept.pop()
    block = [
        "# tuya-bulb-mcp configuration (generated by setup_wizard.py)",
        "# DO NOT COMMIT — contains the local device key.",
    ] + ["%s=%s" % (key, values[key]) for key in MANAGED_KEYS]
    atomic_write(path, "\n".join(kept + ([""] if kept else []) + block) + "\n")


def ask(label, default="", required=False):
    while True:
        shown = " [%s]" % default if default else ""
        val = input("  %s%s: " % (label, shown)).strip()
        val = val or default
        if val or not required:
            return val
        print("    This field is required.")


def ask_yes(label, default=True):
    answer = input("  %s [%s]: " % (label, "Y/n" if default else "y/N")).strip().lower()
    if not answer:
        return default
    return answer in ("y", "yes")


def read_secret(prompt):
    if sys.stdin.isatty():
        return getpass.getpass(prompt)
    # For automation only. Avoid echoing stdin or passing credentials as CLI args.
    print(prompt, end="", flush=True)
    return sys.stdin.readline().rstrip("\r\n")


def run_scan():
    print("\n[..] Scanning the local network for Tuya devices...\n")
    try:
        subprocess.run(
            [sys.executable, "-m", "tinytuya", "scan", "18", "-nocolor", "-yes"],
            check=True,
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        print("[WARN] Scan failed (%s). Enter device details manually." % type(exc).__name__)
        return False
    print("\n  Use the discovered device ID, IP address, and protocol version below.")
    return True


def validate_values(device_id, ip, version, key):
    if not re.fullmatch(r"[A-Za-z0-9_-]+", device_id):
        raise ValueError("Device ID must contain only letters, digits, '-' or '_'.")
    try:
        address = ipaddress.ip_address(ip)
    except ValueError as exc:
        raise ValueError("Enter a valid device IPv4 address.") from exc
    if (address.version != 4 or address.is_multicast or address.is_unspecified
            or address.is_loopback or address.is_reserved):
        raise ValueError("Enter a valid unicast device IPv4 address (not loopback/broadcast).")
    if version not in ("3.3", "3.4"):
        raise ValueError("Supported protocol versions: 3.3 or 3.4.")
    if len(key) != 16 or any(c in key for c in "\r\n"):
        raise ValueError("The device local key must be 16 characters.")


def valid_dps(data):
    if not isinstance(data, dict):
        return False
    dps = data.get("dps")
    if not isinstance(dps, dict) or not all(k in dps for k in WRITABLE_DPS):
        return False
    colour = dps["24"]
    if not isinstance(colour, str) or re.fullmatch(r"[0-9a-fA-F]{12}", colour) is None:
        return False
    hue, sat, val = (int(colour[i:i + 4], 16) for i in (0, 4, 8))
    return (
        isinstance(dps["20"], bool)
        and dps["21"] in ("white", "colour")
        and all(type(dps[k]) is int and 0 <= dps[k] <= 1000 for k in ("22", "23"))
        and 0 <= hue <= 360 and 0 <= sat <= 1000 and 0 <= val <= 1000
    )


def capture_baseline(dps, device_id):
    """Capture once, bound to device identity; never overwrite another device."""
    if os.path.exists(BASELINE_PATH):
        try:
            with open(BASELINE_PATH, encoding="utf-8") as fh:
                existing = json.load(fh)
        except (OSError, ValueError) as exc:
            raise ValueError("Existing baseline is unreadable; review it manually.") from exc
        if not isinstance(existing, dict) or existing.get("device_id") != device_id:
            raise ValueError(
                "Existing baseline belongs to a different or unidentified device. "
                "Back it up and remove it manually before capturing a new baseline."
            )
        if not valid_dps({"dps": existing.get("baseline_dps")}):
            raise ValueError(
                "Existing baseline has invalid datapoints. Back it up and remove "
                "it manually before capturing a new baseline."
            )
        print("[OK] Existing baseline preserved for this device.")
        return
    snapshot = {
        "device_id": device_id,
        "captured_at": datetime.now(timezone.utc).isoformat(),
        "baseline_dps": {k: dps[k] for k in WRITABLE_DPS},
    }
    atomic_write(BASELINE_PATH, json.dumps(snapshot, indent=2) + "\n")
    print("[OK] Initial baseline saved locally (baseline_state.json).")


def verify(values):
    """Only status() is called. No datapoint writes."""
    print("\n[..] Read-only verification...")
    try:
        import tinytuya
        device = tinytuya.BulbDevice(
            values["TUYA_BULB_DEVICE_ID"], values["TUYA_BULB_IP"],
            values["TUYA_BULB_LOCAL_KEY"],
            dev_type="default", version=float(values["TUYA_BULB_VERSION"]),
            connection_timeout=6, connection_retry_limit=2, connection_retry_delay=1,
        )
        device.set_version(float(values["TUYA_BULB_VERSION"]))
        device.set_socketTimeout(8)
        response = device.status()
    except Exception as exc:
        detail = str(exc).replace(values["TUYA_BULB_LOCAL_KEY"], "[REDACTED]")
        print("[FAIL] Verification error (%s): %s" % (type(exc).__name__, detail))
        return False

    if not valid_dps(response):
        mode = (response.get("dps") or {}).get("21") if isinstance(response, dict) and isinstance(response.get("dps"), dict) else None
        if mode in ("scene", "music"):
            print("[FAIL] Device is in %s mode. Switch to white or colour mode in the app, then run setup again." % mode)
        else:
            print("[FAIL] Unsupported or incomplete device status (expected DP20–24).")
        return False
    dps = response["dps"]
    power = "on" if dps["20"] else "off"
    print("[OK] Device responded — power=%s mode=%s DP22=%s DP23=%s" %
          (power, dps["21"], dps["22"], dps["23"]))
    try:
        capture_baseline(dps, values["TUYA_BULB_DEVICE_ID"])
    except (OSError, ValueError) as exc:
        # Never print exception details from I/O paths that may contain secrets.
        if isinstance(exc, ValueError):
            print("[FAIL] %s" % str(exc))
        else:
            print("[FAIL] Could not save baseline (%s)." % type(exc).__name__)
        return False
    print("     (read-only check — no device writes)")
    return True


def main():
    parser = argparse.ArgumentParser(description="Configure a Tuya bulb MCP server.")
    parser.add_argument("--scan", action="store_true", help="scan for devices before prompting")
    parser.add_argument("--no-verify", action="store_true", help="skip read-only status verification")
    args = parser.parse_args()

    print("tuya-bulb-mcp — setup wizard\n")
    current = load_env(ENV_PATH)
    if args.scan:
        run_scan()
    try:
        device_id = ask("Device ID", current.get("TUYA_BULB_DEVICE_ID", ""), required=True)
        ip = ask("Device IP", current.get("TUYA_BULB_IP", ""), required=True)
        version = ask("Protocol version", current.get("TUYA_BULB_VERSION", "3.3"))
        has_key = bool(current.get("TUYA_BULB_LOCAL_KEY"))
        hint = " (blank keeps current key)" if has_key else " (hidden input)"
        key = read_secret("  Local key%s: " % hint).strip()
        key = key or current.get("TUYA_BULB_LOCAL_KEY", "")
        validate_values(device_id, ip, version, key)
        existing_guard = current.get("TUYA_BULB_EXPECTED_DEVICE_ID", "")
        guard = ask_yes(
            "Enable configured-device identity guard?",
            not existing_guard or existing_guard == device_id,
        )
    except EOFError:
        print("\n[FAIL] Input ended before setup was complete.")
        return 1
    except (ValueError, KeyboardInterrupt) as exc:
        print("\n[FAIL] %s" % (str(exc) if isinstance(exc, ValueError) else "Setup cancelled."))
        return 1

    values = {
        "TUYA_BULB_DEVICE_ID": device_id,
        "TUYA_BULB_IP": ip,
        "TUYA_BULB_VERSION": version,
        "TUYA_BULB_LOCAL_KEY": key,
        "TUYA_BULB_EXPECTED_DEVICE_ID": device_id if guard else "",
    }
    # Verification must pass before replacing a previously working configuration.
    had_baseline = os.path.exists(BASELINE_PATH)
    if not args.no_verify and not verify(values):
        print("[FAIL] Existing .env configuration was left unchanged.")
        return 2
    # A failed .env update must not leave a freshly captured baseline
    # tied to a device different from the unchanged configuration.
    created_baseline = not args.no_verify and not had_baseline and os.path.isfile(BASELINE_PATH)
    try:
        upsert_env(ENV_PATH, values)
    except OSError as exc:
        if created_baseline:
            try:
                os.unlink(BASELINE_PATH)
                print("[WARN] New baseline rolled back after .env failure.")
            except OSError:
                print("[WARN] Could not roll back new baseline; inspect it before retrying.")
        print("[FAIL] Could not update .env (%s)." % type(exc).__name__)
        return 1
    print("[OK] Configuration saved to .env.")
    if args.no_verify:
        print("[WARN] Device compatibility and baseline not checked (--no-verify).")
    print("\nMCP client command: %s" % sys.executable)
    print("MCP client args: %s" % os.path.join(BASE, "tuya_bulb_mcp_server.py"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
